-- Creator analytics storage (docs/features/creator-analytics-contract.md "Storage"): what consenting visitors do on public /e
-- publications, keyed by the publication's canvas (org, canvas), never by its replaceable token. Written only by the ingest route and the
-- Rabbit Hole start and fork success paths (publication-analytics.js), and only with the visitor's analytics consent. Learner keys are
-- one-way hashes: pseudonymous, not anonymous. No users.id, visitor id, email, IP, user agent, referrer or free text is stored.
-- Every table with a learner_key or session_key expires after 90 days (a product default): reads ignore older rows, a daily scheduled
-- cleanup deletes them, and each ingest and read purges them as a safeguard. publication_board_days and publication_revisions hold no per-person column and are kept for the life of the canvas.
-- Additive and re-runnable; LEARN_DB only. Production: an owner command, applied immediately before the release that reads it.
CREATE TABLE IF NOT EXISTS publication_events (
  event_id TEXT PRIMARY KEY,
  org TEXT NOT NULL,
  canvas TEXT NOT NULL,
  session_key TEXT NOT NULL,
  learner_key TEXT NOT NULL,
  type TEXT NOT NULL,
  received_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS publication_events_session ON publication_events (session_key, received_at);
CREATE INDEX IF NOT EXISTS publication_events_canvas ON publication_events (org, canvas, received_at);
CREATE INDEX IF NOT EXISTS publication_events_received ON publication_events (received_at);
CREATE INDEX IF NOT EXISTS publication_events_learner ON publication_events (learner_key);
-- One row per learner and publication: signed in or not, synthetic (an identifiable check, never reported as audience), when last seen,
-- and the end of the last credited active interval, so overlapping tabs cannot credit the same wall-clock second twice.
CREATE TABLE IF NOT EXISTS publication_learners (
  org TEXT NOT NULL,
  canvas TEXT NOT NULL,
  learner_key TEXT NOT NULL,
  signed_in INTEGER NOT NULL DEFAULT 0,
  synthetic INTEGER NOT NULL DEFAULT 0,
  last_seen_at TEXT NOT NULL,
  credited_through TEXT,
  PRIMARY KEY (org, canvas, learner_key)
);
CREATE INDEX IF NOT EXISTS publication_learners_seen ON publication_learners (last_seen_at);
CREATE INDEX IF NOT EXISTS publication_learners_learner ON publication_learners (learner_key);
-- One row per visit of one identity: the session key is derived from the learner, so a sign-out or an account switch starts a new visit.
CREATE TABLE IF NOT EXISTS publication_sessions (
  session_key TEXT PRIMARY KEY,
  org TEXT NOT NULL,
  canvas TEXT NOT NULL,
  learner_key TEXT NOT NULL,
  started_at TEXT NOT NULL,
  reported_active INTEGER NOT NULL DEFAULT 0,
  credited_active INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS publication_sessions_started ON publication_sessions (started_at);
CREATE INDEX IF NOT EXISTS publication_sessions_learner ON publication_sessions (learner_key);
-- One row per learner, publication, UTC day and revision segment: opens, credited active seconds, the day's first source (an allowlisted
-- category) and campaign (an approved id, web/src/analytics-campaigns.js).
CREATE TABLE IF NOT EXISTS publication_learner_days (
  org TEXT NOT NULL,
  canvas TEXT NOT NULL,
  learner_key TEXT NOT NULL,
  day TEXT NOT NULL,
  segment INTEGER NOT NULL,
  opens INTEGER NOT NULL DEFAULT 0,
  active_seconds INTEGER NOT NULL DEFAULT 0,
  source TEXT,
  campaign TEXT,
  PRIMARY KEY (org, canvas, learner_key, day, segment)
);
CREATE INDEX IF NOT EXISTS publication_learner_days_day ON publication_learner_days (org, canvas, day);
CREATE INDEX IF NOT EXISTS publication_learner_days_expiry ON publication_learner_days (day);
CREATE INDEX IF NOT EXISTS publication_learner_days_learner ON publication_learner_days (learner_key);
-- Per learner, day and item: kind card_seen | card_acted | concept_seen | concept_explored | concept_deeper | resource | step_shown |
-- step_selected | quiz | start | fork. Item ids are checked against the published board or generated by the server; never free text.
-- n counts repeats; extra is a Next Step position or a quiz outcome (1 correct).
CREATE TABLE IF NOT EXISTS publication_learner_items (
  org TEXT NOT NULL,
  canvas TEXT NOT NULL,
  learner_key TEXT NOT NULL,
  day TEXT NOT NULL,
  segment INTEGER NOT NULL,
  kind TEXT NOT NULL,
  item_id TEXT NOT NULL,
  n INTEGER NOT NULL DEFAULT 1,
  extra INTEGER,
  PRIMARY KEY (org, canvas, learner_key, day, segment, kind, item_id)
);
CREATE INDEX IF NOT EXISTS publication_learner_items_day ON publication_learner_items (org, canvas, day);
CREATE INDEX IF NOT EXISTS publication_learner_items_expiry ON publication_learner_items (day);
CREATE INDEX IF NOT EXISTS publication_learner_items_learner ON publication_learner_items (learner_key);
-- The long-lived counters: per publication and UTC day, sums only. No learner, session, event or source-of-a-person column.
CREATE TABLE IF NOT EXISTS publication_board_days (
  org TEXT NOT NULL,
  canvas TEXT NOT NULL,
  day TEXT NOT NULL,
  opens INTEGER NOT NULL DEFAULT 0,
  opens_from_stars INTEGER NOT NULL DEFAULT 0,
  rabbit_holes_started INTEGER NOT NULL DEFAULT 0,
  audience_forks INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (org, canvas, day)
);
-- Revision segments: each board version seen by ingest, with its card set. A segment starts at the first version whose card set (card
-- ids and their concepts) differs from the version before it; text edits, moves and resizes keep the segment. No per-person column.
CREATE TABLE IF NOT EXISTS publication_revisions (
  org TEXT NOT NULL,
  canvas TEXT NOT NULL,
  version INTEGER NOT NULL,
  card_set_key TEXT NOT NULL,
  segment INTEGER NOT NULL,
  first_seen_at TEXT NOT NULL,
  PRIMARY KEY (org, canvas, version)
);
-- Collection metadata: collection_started_at, last_ingest_at, last_ingest_error_at, last_cleanup_ok_at, last_cleanup_error_at.
CREATE TABLE IF NOT EXISTS analytics_meta (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
