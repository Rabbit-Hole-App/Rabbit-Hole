// Generates src/explanation-prompts.generated.js from the editable section files in src/prompts/explanation/**/*.md (same precedent as build-tutor-prompts.mjs).
// A Cloudflare Worker cannot read files at runtime and node cannot import .md, so the text is bundled as a plain JS module.
// The .md files stay the source: edit them, then `npm run prompts:build:explanation` (test/explanation-prompt-files.test.js fails while the module is stale).
// A file's text is its content with CRLF as LF and exactly one final newline removed; each entry carries the sha256 of that text.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../src/prompts/explanation/', import.meta.url));
const out = fileURLToPath(new URL('../src/explanation-prompts.generated.js', import.meta.url));

const walk = (dir, prefix = '') => readdirSync(dir, { withFileTypes: true })
  .flatMap(entry => entry.isDirectory() ? walk(`${dir}${entry.name}/`, `${prefix}${entry.name}/`) : entry.name.endsWith('.md') ? [`${prefix}${entry.name}`] : [])
  .sort();

export function renderExplanationPrompts() {
  const entries = walk(root).map(path => {
    const text = readFileSync(`${root}${path}`, 'utf8').replace(/\r\n/g, '\n').replace(/\n$/, '');
    return `  ${JSON.stringify(path)}: { sha256: '${createHash('sha256').update(text).digest('hex')}', text: ${JSON.stringify(text)} },`;
  });
  return `// GENERATED by scripts/build-explanation-prompts.mjs from src/prompts/explanation/**/*.md. Do not edit: edit the .md files, then run \`npm run prompts:build:explanation\`.\nexport const EXPLANATION_PROMPT_FILES = Object.freeze({\n${entries.join('\n')}\n});\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeFileSync(out, renderExplanationPrompts());
