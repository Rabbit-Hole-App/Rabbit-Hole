// Generates src/tutor-prompts.generated.js from the editable prompt files in src/prompts/tutor/**/*.md.
// A Cloudflare Worker cannot read files at runtime and node cannot import .md, so the prompt text is bundled as a plain JS module.
// The .md files stay the source: edit them, then `npm run prompts:build` (test/tutor-prompt.test.js fails while the module is stale).
// Each entry carries the sha256 of the file's text (LF line endings), the hash every model call's record names.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../src/prompts/tutor/', import.meta.url));
const out = fileURLToPath(new URL('../src/tutor-prompts.generated.js', import.meta.url));

const walk = (dir, prefix = '') => readdirSync(dir, { withFileTypes: true })
  .flatMap(entry => entry.isDirectory() ? walk(`${dir}${entry.name}/`, `${prefix}${entry.name}/`) : entry.name.endsWith('.md') ? [`${prefix}${entry.name}`] : [])
  .sort();

export function renderTutorPrompts() {
  const entries = walk(root).map(path => {
    const text = readFileSync(`${root}${path}`, 'utf8').replace(/\r\n/g, '\n');
    return `  ${JSON.stringify(path)}: { sha256: '${createHash('sha256').update(text).digest('hex')}', text: ${JSON.stringify(text)} },`;
  });
  return `// GENERATED by scripts/build-tutor-prompts.mjs from src/prompts/tutor/**/*.md. Do not edit: edit the .md files, then run \`npm run prompts:build\`.\nexport const TUTOR_PROMPT_FILES = Object.freeze({\n${entries.join('\n')}\n});\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeFileSync(out, renderTutorPrompts());
