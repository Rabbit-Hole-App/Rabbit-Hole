function load(file, width = 1460) {
  const location = new URL(file, 'file:///ui/');
  const html = fs.readFileSync(path.join(__dirname, '../clean', path.basename(location.pathname)), 'utf8');
  const { document, window } = parseHTML(html);
  window.location = location;
  Object.defineProperty(document, 'activeElement', { get: () => document.focusedElement });
  window.HTMLElement.prototype.focus = function () { this.ownerDocument.focusedElement = this; };
  window.HTMLElement.prototype.getBoundingClientRect = () => ({ left: 200, right: 260, bottom: 120 });
  window.HTMLElement.prototype.showModal = function () { this.open = true; };
  window.HTMLElement.prototype.close = function () { this.open = false; };
  const storage = new Map();
  const timers = new Map();
  let timerId = 0;
  window.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
  const context = vm.createContext({
    document, window, innerWidth: width, innerHeight: 900, console, URLSearchParams,
    ResizeObserver: class { observe() {} },
    matchMedia: () => ({ matches: width <= 700 }),
    setTimeout: (callback, delay) => { timers.set(++timerId, { callback, delay }); return timerId; },
    clearTimeout: id => timers.delete(id),
  });
  for (const script of document.querySelectorAll('script')) vm.runInContext(script.textContent, context, { filename: file });
  function runTimers(delay) {
    for (const [id, task] of [...timers]) {
      if (task.delay !== delay || !timers.has(id)) continue;
      timers.delete(id);
      task.callback();
    }
  }
  return { document, window, storage, runTimers, $: id => document.getElementById(id) };
}

function key(view, target, value) {
  const event = new view.window.Event('keydown', { bubbles: true, cancelable: true });
  Object.defineProperty(event, 'key', { value });
  target.dispatchEvent(event);
}

function search(view, value, settle = true) {
  const input = view.$('explore-search');
  input.value = value;
  input.dispatchEvent(new view.window.Event('input', { bubbles: true }));
  if (settle) view.runTimers(250);
}

