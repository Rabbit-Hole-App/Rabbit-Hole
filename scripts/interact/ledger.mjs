// Appends one /interact job's benchmark row to docs/features/interact/benchmarks/ledger.jsonl and regenerates ledger.md (build-half sprint item 1).
//   node scripts/interact/ledger.mjs --clone <clone origin> --job <id> --board <id>      fetch ?detail=1 with the launcher session (HTTP only)
//   node scripts/interact/ledger.mjs --from <saved detail.json> [--dir <folder>]          the same from a saved response, no network (the dry run)
// The session is minted as the evidence scripts do (poll-job.mjs): the test bypass key is read BY NAME from small-deploy/.env, never printed.
import { appendFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LEDGER_COLUMNS, jobFromDetail, ledgerMarkdown, ledgerRow } from '../../packages/control-plane/src/interact-ledger.js';

const HERE = dirname(fileURLToPath(import.meta.url));
export const LEDGER_DIR = join(HERE, '..', '..', 'docs', 'features', 'interact', 'benchmarks');
const SPEC = 'C:/s/spec/interact-real/current.json', ENV = 'C:/Users/cyudhist/Desktop/workspace/small-deploy/.env';
const UA = { 'User-Agent': 'rabbit-hole-owner-launcher/1' };

// The server's own row when the clone computes one (diagnostics.ledger), else the row of the same fields in the response (the saved run-15 evidence).
export const rowOfDetail = detail => detail?.diagnostics?.ledger ?? ledgerRow(jobFromDetail(detail));

// One line per row, one job once: a repeat of a job replaces its line, so a rerun never doubles a result.
export function appendRow(row, dir = LEDGER_DIR) {
  mkdirSync(dir, { recursive: true });
  const file = join(dir, 'ledger.jsonl');
  let rows = [];
  try { rows = readFileSync(file, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l)); } catch { /* no ledger yet */ }
  return writeRows([...rows.filter(r => r.jobId !== row.jobId), row], dir);
}

// timing=v1 rows keep the numbers they were recorded with (their stage columns were the stage records' sums; msRun and msCheck read 0 on the clone's frozen isolate clock); timing=v2 rows are the contiguous
// wall-clock slices of Generate to ready that add up to msTotal (interact-ledger.js ledgerRow), with msJudge, the shadow judge after delivery, outside msTotal.
export function writeRows(rows, dir = LEDGER_DIR) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'ledger.jsonl'), rows.map(r => JSON.stringify(r)).join('\n') + '\n');
  writeFileSync(join(dir, 'ledger.md'), `# /interact benchmark ledger\n\nFactual columns first (${LEDGER_COLUMNS.slice(0, LEDGER_COLUMNS.indexOf('costUsd') + 1).join(', ')}), then milliseconds per stage. Generated by scripts/interact/ledger.mjs from ledger.jsonl; empty = not recorded.\n\ntiming=v1 rows keep the numbers they were recorded with (stage columns were the stage records' sums; msRun and msCheck read 0 on the clone's frozen isolate clock). timing=v2 stage columns are contiguous wall-clock slices of Generate to ready that add up to msTotal; msJudge (the shadow judge) runs after delivery and is outside it.\n\n${ledgerMarkdown(rows)}`);
  return rows.length;
}

async function fetchDetail({ clone, job, board }) {
  const spec = JSON.parse(readFileSync(SPEC, 'utf8'));
  const secret = (readFileSync(ENV, 'utf8').match(/^RABBIT_HOLE_DEV_TEST_BYPASS=(.*)$/m)?.[1] || '').trim().replace(/^['"]|['"]$/g, '');
  const minted = await fetch('https://rabbit-hole-cp-dev.tryrabbithole.workers.dev/test/session', { method: 'POST', headers: { ...UA, 'Content-Type': 'application/json' }, body: JSON.stringify({ email: spec.email, secret }) });
  const { session } = await minted.json();
  const r = await fetch(`${clone.replace(/\/$/, '')}/api/learn/explain/jobs/${job}?board=${board}&detail=1`, { headers: { ...UA, cookie: `small_session=${session}` } });
  if (!r.ok) throw new Error(`detail=1 answered ${r.status}`);
  return r.json();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const arg = name => process.argv[process.argv.indexOf(`--${name}`) + 1];
  const has = name => process.argv.includes(`--${name}`);
  try {
    const detail = has('from') ? JSON.parse(readFileSync(arg('from'), 'utf8')) : await fetchDetail({ clone: arg('clone'), job: arg('job'), board: arg('board') });
    const row = rowOfDetail(detail);
    if (row.result === 'running') throw new Error(`job ${row.jobId} has not finished; nothing appended`);
    console.log(`ledger rows: ${appendRow(row, has('dir') ? arg('dir') : LEDGER_DIR)} (${row.jobId} ${row.result})`);
  } catch (error) { console.error(`ledger: ${error.message}`); process.exit(1); }
}
