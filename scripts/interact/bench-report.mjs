#!/usr/bin/env node
// scripts/interact/bench-report.mjs (owner brief 2026-11-13 14:20, section 1): bench-author.jsonl -> bench-author.md. Per model x depth: attempts, first-try pass rate, the pass rate with one repair (rounds 1), median
// msAuthor, msTotal and cost, and the top 3 first problems by count (round 0 failures). A first-try problem is grouped by its text with numbers replaced, so one cause counts once.
//   node scripts/interact/bench-report.mjs [--validator v1|v2] [--in <jsonl>] [--out <md>]
import { parseArgs } from 'node:util';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BENCH_DIR } from './bench-author.mjs';

const median = values => { const a = values.filter(v => v != null).sort((x, y) => x - y); return a.length ? (a.length % 2 ? a[(a.length - 1) / 2] : (a[a.length / 2 - 1] + a[a.length / 2]) / 2) : null; };
const group = problem => String(problem).replace(/\d+(\.\d+)?/g, 'N').slice(0, 160);
const fmt = (v, digits = 1) => (v == null ? 'n/a' : v.toFixed(digits));

// rows -> markdown. An attempt is the rows sharing ts, plan and model.
export function benchReport(rows, { validator } = {}) {
  rows = rows.filter(r => !validator || r.validator === validator);
  const keyOf = r => `${r.model}|${r.depth}`, order = ['brief', 'balanced', 'detailed'], groups = new Map();
  for (const r of rows) { if (!groups.has(keyOf(r))) groups.set(keyOf(r), []); groups.get(keyOf(r)).push(r); }
  const lines = [`# bench-author${validator ? ` (validator=${validator})` : ''}`, '', 'Generated by scripts/interact/bench-report.mjs from docs/features/interact/benchmarks/bench-author.jsonl. A first try is round 0; "with 1 repair" counts an attempt that passed at round 0 or after one correction by the same model.', '',
    '| model | depth | attempts | first-try pass | with 1 repair | median author s | median total s | median cost $ | top first problems (first try) |', '|---|---|---|---|---|---|---|---|---|'];
  for (const [key, g] of [...groups].sort(([a], [b]) => { const [ma, da] = a.split('|'), [mb, db] = b.split('|'); return ma.localeCompare(mb) || order.indexOf(da) - order.indexOf(db); })) {
    const [model, depth] = key.split('|'), first = g.filter(r => r.round === 0), repaired = g.filter(r => r.round > 0);
    const attempts = first.length, firstPass = first.filter(r => r.result === 'pass').length;
    const withRepair = firstPass + first.filter(r => r.result !== 'pass' && repaired.some(x => x.ts === r.ts && x.plan === r.plan && x.result === 'pass')).length;
    const counts = new Map();
    for (const r of first) if (r.result !== 'pass') counts.set(group(r.firstProblem), (counts.get(group(r.firstProblem)) ?? 0) + 1);
    const top = [...counts].sort((a, b) => b[1] - a[1]).slice(0, 3).map(([text, c]) => `${c}x ${text.replace(/\|/g, '/')}`).join('<br>');
    lines.push(`| ${model} | ${depth} | ${attempts} | ${firstPass}/${attempts} | ${repaired.length ? `${withRepair}/${attempts}` : 'n/a'} | ${fmt(median(first.map(r => r.msAuthor)) / 1000, 2)} | ${fmt(median(first.map(r => r.msTotal)) / 1000, 2)} | ${fmt(median(first.map(r => r.costUsd)), 4)} | ${top || 'none'} |`);
  }
  const spent = rows.reduce((s, r) => s + (r.costUsd ?? 0), 0);
  lines.push('', `${rows.length} model calls, $${spent.toFixed(4)} in total.`, '');
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values: a } = parseArgs({ options: { validator: { type: 'string' }, in: { type: 'string', default: join(BENCH_DIR, 'bench-author.jsonl') }, out: { type: 'string', default: join(BENCH_DIR, 'bench-author.md') } }, strict: true });
  if (!existsSync(a.in)) { console.error(`x no ${a.in}`); process.exit(2); }
  const rows = readFileSync(a.in, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l)), md = benchReport(rows, { validator: a.validator });
  writeFileSync(a.out, md); console.log(md);
}
