// Brief 32 card A: bakes the flow layout of the tree-trace spec into frame coordinates, the way FrameFigures.jsx DiagramFigure scales a diagram (never larger than natural size, down to fit the box the
// frame leaves below it) and renderTutorDiagram places it (the layout sits under a title band). Writes packages/web/src/interact-tree-motion-geometry.js; `--check` only compares.
// Reads tutor-diagrams/ and changes nothing there. Rerun after any change to the spec below or to the frame/diagram box.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'packages/web/src');
const FRAME = { width: 640, height: 290 }, BOX = { x: 12, y: 12, w: 420 };
const TREE = {
  title: 'Decision tree',
  nodes: [
    { id: 'root', label: 'x ≤ 4?', role: 'decision' }, { id: 'rootl', label: 'Class 0 · 4 rows', role: 'outcome' }, { id: 'rootr', label: 'y ≤ 2?', role: 'decision' },
    { id: 'rootrl', label: 'Class 0 · 1 row', role: 'outcome' }, { id: 'rootrr', label: 'Class 1 · 3 rows', role: 'outcome' },
  ],
  edges: [{ from: 'root', to: 'rootl', label: 'Yes' }, { from: 'root', to: 'rootr', label: 'No' }, { from: 'rootr', to: 'rootrl', label: 'Yes' }, { from: 'rootr', to: 'rootrr', label: 'No' }],
};
const load = name => import(pathToFileURL(join(SRC, name)));
const { layoutFlow } = await load('tutor-diagrams/flow.js'), { renderTutorDiagram } = await load('tutor-diagrams/TutorDiagram.js'), { parseTutorDiagram } = await load('tutor-diagrams/spec.js');
const spec = { version: 1, diagram: { kind: 'flow', ...TREE } };
const rendered = renderTutorDiagram(spec, BOX.w), layout = layoutFlow(parseTutorDiagram(spec).diagram, BOX.w);
const title = rendered.height - layout.height, scale = Math.min(1, BOX.w / rendered.width, (FRAME.height - BOX.y) / rendered.height);
const r2 = n => Math.round(n * 100) / 100, at = (x, y) => [r2(BOX.x + scale * x), r2(BOX.y + scale * (title + y))];
const geometry = {
  frame: FRAME, box: BOX, scale: r2(scale), rendered: { width: rendered.width, height: rendered.height },
  nodes: Object.fromEntries(layout.geometry.nodes.map(n => [n.id, { centre: at(n.x + n.width / 2, n.y + n.height / 2), box: [...at(n.x, n.y), r2(scale * n.width), r2(scale * n.height)] }])),
  edges: Object.fromEntries(layout.geometry.edges.map(e => [`${e.from}:${e.to}`, e.points.map(([x, y]) => at(x, y))])),
  labels: Object.fromEntries(layout.geometry.edges.filter(e => e.label).map(e => [`${e.from}:${e.to}`, [...at(e.label.x, e.label.y), r2(scale * e.label.width), r2(scale * e.label.height)]])),
};
const text = `// Generated by scripts/interact/bake-tree-geometry.mjs (brief 32): the tree-trace flow laid out at the width the card gives the diagram, in frame coordinates. Do not edit by hand.\nexport const TREE_GEOMETRY = ${JSON.stringify(geometry)};\n`;
const file = join(SRC, 'interact-tree-motion-geometry.js');
if (process.argv.includes('--check')) { const same = readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === text; console.log(same ? 'geometry is current' : 'geometry is STALE'); process.exit(same ? 0 : 1); }
writeFileSync(file, text);
console.log(`wrote ${file}; scale ${geometry.scale}`);
