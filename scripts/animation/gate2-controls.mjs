// Gate 2 controls (owner standing rules, from C10): job 0 and the reviewer calibration set. Run by sgd-qualify.mjs before any author job, or alone
// (`sgd-qualify.mjs --controls`). Read docs/features/animation/gate2-qualification.md, "Controls".
//
// Job 0: the golden SGD artifact (packages/web/src/animation3d/testdata/sgd-golden.json) must PASS review. If the reviewer REJECTS it the candidate is a harness
// bug by definition, and nothing paid is started (exit 5). Calibration (--calibrate <manifest.json>): the golden must pass and every listed retained draft must
// FAIL with its known findings; a draft that passes or lacks a known finding is a drift of the reviewer (its prompt or page changed), printed by name.
//
// HOW AN ARTIFACT GETS REVIEWED. No route runs the product's review stage on a GIVEN artifact (seed-outcomes writes canned failed jobs; seed-fixture stores a
// SAVED RESULT, no job and no stage), so each item is done in four steps, the first three free:
//   1. seed-fixture: the artifact is stored as an offline-fixture saved result on a fresh canvas of the first test session (dev-only route; the title and
//      description must say "Offline fixture", which a draft gets as a prefix);
//   2. render-result: the preview's own deployed capture path draws it (the review's own manifest) and returns the PNGs and traces;
//   3. the candidate's own reviewStage (animation-review.js, imported from the candidate worktree: its prompt, tool, request builder, retry and acceptance rule)
//      is run on those captures;
//   4. its one model call is sent straight to the provider with the dev key (read BY NAME from the credentials file, held in memory, never printed): OUTSIDE the
//      product's ledger, so it is not in the test user's allowance or the platform day cap, only in spend-rows.md (about 12 to 16 credits per item).
import { createHash } from 'node:crypto';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const CONTROLS_SCHEMA = 'gate2-controls/1';
export const CALIBRATION_SCHEMA = 'gate2-calibration/1';
export const GOLDEN_REQUEST = 'stochastic gradient descent'; // the learner request the reviewer is shown for the golden (Gate 2 phrasing 1)
export const REVIEW_CREDITS_EXPECTED = 20; // cap headroom per review (measured 12 to 16 credits, with a margin)
const TITLE_MARK = 'Offline fixture: ', DESCRIPTION_MARK = 'OFFLINE FIXTURE, not generated by a model. ';
const EMPTY_BOARD = { strokes: [], shapes: [], items: [], links: [], groups: [], areas: [], exchanges: [], blocks: [] };
const DIAG = '/api/learn/animation/diagnostics';
const sha = text => createHash('sha256').update(text).digest('hex');

// The candidate's own functions, imported from its worktree (the files the preview was built from).
export async function loadProduct(worktree) {
  const at = file => import(pathToFileURL(join(worktree, 'packages', 'control-plane', 'src', file)).href);
  const [review, policy, author, models] = await Promise.all([at('animation-review.js'), at('animation-policy.js'), at('animation-author.js'), at('learn-models.js')]);
  return { reviewStage: review.reviewStage, animationRequest: policy.animationRequest, animationModel: policy.animationModel, sealArtifact: author.sealArtifact, costUsd: models.costUsd };
}

// ---- the items ----
// A fixture says so in its title and description (seed-fixture refuses anything else); a draft gets the marks as a prefix, a golden that has them is left as it is.
export function relabel(artifact) {
  const title = String(artifact.title ?? 'scene'), description = String(artifact.description ?? '');
  return { ...artifact,
    title: title.startsWith(TITLE_MARK) ? title : `${TITLE_MARK}${title}`.slice(0, 120),
    description: description.startsWith(DESCRIPTION_MARK.trim()) ? description : `${DESCRIPTION_MARK}${description}`.slice(0, 600) };
}
const readJson = file => JSON.parse(readFileSync(file, 'utf8'));
const inside = (base, p) => (isAbsolute(p) ? p : resolve(base, p));

// The manifest of the calibration drafts (lane (d) picks them from the retained evidence):
//   { "schema": "gate2-calibration/1", "items": [ { "name": "...", "expect": "fail", "request": "...", "knownFindings": ["regex", ...],
//       "diagnostics": "<path to a job's diagnostics-detail1.json>", "draft": "last" | "before-repair-N"        (the job's plan and one of its retained drafts)
//     or  "artifact": "<path to a draft or artifact JSON>", "plan": "<path to the approved plan JSON>" } ] }
// Paths are relative to the manifest. -> [{ name, kind: 'draft', expect, request, knownFindings: [string], plan, draft, planHash }]
export function readManifest(file) {
  const base = dirname(resolve(file)), raw = readJson(file);
  if (raw?.schema !== CALIBRATION_SCHEMA || !Array.isArray(raw.items) || !raw.items.length) throw new Error(`${file} is not a ${CALIBRATION_SCHEMA} manifest with items`);
  const names = new Set();
  return raw.items.map((item, i) => {
    const name = String(item.name ?? '').trim();
    if (!name || names.has(name)) throw new Error(`manifest item ${i + 1}: a distinct name is required`);
    names.add(name);
    const expect = item.expect ?? 'fail';
    if (!['pass', 'fail'].includes(expect)) throw new Error(`${name}: expect is pass or fail`);
    const known = (item.knownFindings ?? []).map(String);
    if (expect === 'fail' && !known.length) throw new Error(`${name}: a draft that must fail needs knownFindings (patterns over the reviewer's messages)`);
    for (const pattern of known) new RegExp(pattern, 'i'); // a bad pattern fails here, before any spend
    let plan, draft, planHash = null;
    if (item.diagnostics) {
      const export_ = readJson(inside(base, item.diagnostics)), diag = export_.diagnostics ?? {};
      const which = String(item.draft ?? 'last'), repair = /^before-repair-(\d+)$/.exec(which);
      draft = which === 'last' ? diag.draft : repair ? (diag.candidates ?? []).find(c => c.repairs === Number(repair[1]))?.previousDraft : null;
      if (!draft) throw new Error(`${name}: ${item.diagnostics} has no draft "${which}"`);
      plan = diag.plan; planHash = export_.job?.planHash ?? null;
    } else if (item.artifact && item.plan) { draft = readJson(inside(base, item.artifact)); plan = readJson(inside(base, item.plan)); }
    else throw new Error(`${name}: give diagnostics + draft, or artifact + plan`);
    if (!plan || typeof draft !== 'object') throw new Error(`${name}: the plan or the draft is missing`);
    return { name, kind: 'draft', expect, request: String(item.request ?? GOLDEN_REQUEST), knownFindings: known, plan, draft, planHash };
  });
}
export const readGolden = (file, inline = null) => { const g = inline ?? readJson(file); if (!g?.plan || !g?.artifact) throw new Error(`${file} is not a golden ({ plan, artifact })`); return { name: 'golden SGD artifact (job 0)', kind: 'golden', expect: 'pass', request: GOLDEN_REQUEST, knownFindings: [], plan: g.plan, draft: g.artifact, planHash: g.artifact.planHash ?? null }; };

// ---- judging ----
const findingOf = f => ({ severity: f.severity, category: f.category, verdict: f.verdict, message: String(f.message).replace(/\s+/g, ' ') });
// -> null when the item behaved as expected, else a sentence saying which way the reviewer drifted.
export function judge(item, review) {
  const serious = review.findings.filter(f => f.severity !== 'minor');
  if (item.expect === 'pass') return review.accepted ? null : `rejected, but this must pass: ${serious.slice(0, 3).map(f => `${f.severity}/${f.category} ${String(f.message).slice(0, 120)}`).join(' | ') || 'no serious finding named'}`;
  if (review.accepted) return 'accepted, but this retained draft must fail review (the reviewer has become more lenient)';
  const missing = item.knownFindings.filter(p => !review.findings.some(f => new RegExp(p, 'i').test(String(f.message))));
  return missing.length ? `rejected, but the known finding(s) ${missing.map(m => `/${m}/`).join(', ')} were not reported (the reviewer has changed what it sees)` : null;
}

// The reviewer's one model call, sent straight to the provider (see the header). -> reviewStage's ctx.call
export function providerReview({ product, apiKey, fetchImpl = globalThis.fetch, timeoutMs = 300000 }) {
  return async (_role, spec) => {
    const body = product.animationRequest({ ANTHROPIC_API_KEY: 'shape-check-only' }, 'review', spec);
    const response = await fetchImpl('https://api.anthropic.com/v1/messages', { method: 'POST', signal: AbortSignal.timeout(timeoutMs),
      headers: { 'content-type': 'application/json', 'x-api-key': apiKey, 'anthropic-version': '2023-06-01' }, body: JSON.stringify({ model: product.animationModel('review'), ...body }) });
    const reply = await response.json().catch(() => null);
    if (!response.ok) throw new Error(`the review call answered HTTP ${response.status}${reply?.error?.type ? ` (${reply.error.type})` : ''}`);
    return { input: (reply.content ?? []).find(b => b.type === 'tool_use')?.input ?? null, usage: reply.usage ?? {}, stopReason: reply.stop_reason ?? null, model: reply.model };
  };
}

// ---- the run ----
// cfg: { golden, items: [calibration items], session: { email, call }, product, sha, version, out, concurrency, manifestHash }; deps: { review, log }
// -> { verdict: 'PASS' | 'FAIL', goldenAccepted, items, spentCredits }
export async function runControls(cfg, deps) {
  const { product, session, log } = { ...cfg, ...deps }, call = session.call;
  async function runItem(item, index) {
    const out = { name: item.name, kind: item.kind, expect: item.expect, outcome: 'error', accepted: null, drift: null, findings: [], credits: 0, resultId: null, artifactHash: null, note: '' };
    try {
      const canvas = (await call('POST', '/api/canvases', { title: `Gate 2 control ${index} ${cfg.sha.slice(0, 7)}` })).data?.name;
      const boardId = canvas && (await call('PUT', `/api/learn/boards/${canvas}/main`, { state: EMPTY_BOARD })).data?.board_id;
      if (!boardId) throw new Error('could not make the canvas for the control');
      const draft = relabel(item.draft), planHash = item.planHash ?? sha(JSON.stringify(item.plan));
      const artifact = item.kind === 'golden' ? draft : await product.sealArtifact(draft, { artifactId: `fixture-cal-${index}-${sha(JSON.stringify(item.draft)).slice(0, 8)}`, revision: 1, planHash, createdAt: new Date(0).toISOString() });
      const seeded = await call('POST', `${DIAG}/seed-fixture`, { boardId, artifact });
      if (seeded.status !== 200) throw new Error(`seed-fixture answered HTTP ${seeded.status}${seeded.data?.error ? ` (${String(seeded.data.error).slice(0, 160)})` : ''}${seeded.status === 404 ? ': the preview has no ANIMATION_DIAGNOSTICS' : ''}`);
      const rendered = await call('POST', `${DIAG}/render-result`, { boardId, resultId: seeded.data.resultId });
      if (rendered.status !== 200 || !rendered.data?.ok) throw new Error(`render-result answered HTTP ${rendered.status}${rendered.data?.error ? ` (${String(rendered.data.error).slice(0, 160)})` : ''}`);
      const r = rendered.data, artifactHash = r.identity?.artifactHash ?? r.artifactHash;
      out.resultId = seeded.data.resultId; out.artifactHash = artifactHash;
      // The captures as the render stage records them (inputs from the trace; the probe returns the trace but not the entry's inputs) with their pixels inline.
      const captures = r.captures.map(c => ({ id: c.id, artifactHash, view: c.view, label: c.label, time: c.time, inputs: c.trace?.inputs ?? {}, events: c.events, ...(c.leadTicks ? { leadTicks: c.leadTicks } : {}),
        ticks: c.ticks, trace: c.trace, sha256: c.sha256, mediaType: 'image/png', data: c.pngBase64 }));
      const job = { id: `control-${index}`, prompt: item.request, plan: item.plan, artifact: r.artifact, artifactHash, captures, evidence: [], coverage: r.coverage ?? null, draft, reviews: [], counts: { review: 0 }, attempt: 1, repairs: 0 };
      const ctx = { env: {}, call: async (role, spec) => { const reply = await deps.review(role, spec); out.credits += Math.round(product.costUsd({ model: reply.model ?? product.animationModel('review'), ...reply.usage }) * 1e6) / 1e4; return reply; }, noteReview: async () => {} };
      const review = await product.reviewStage(job, ctx);
      out.accepted = review.accepted; out.outcome = review.accepted ? 'accepted' : 'rejected';
      out.findings = review.findings.map(findingOf); out.imagesReviewed = review.imagesReviewed;
      out.drift = judge(item, review);
    } catch (error) { out.outcome = 'error'; out.note = String(error.message).slice(0, 300); }
    log(`[control ${index}] ${item.name}: ${out.outcome}${out.drift ? ` - DRIFT: ${out.drift}` : out.note ? ` - ${out.note}` : ''}; ${out.credits.toFixed(2)} credits (direct review call)`);
    return out;
  }
  const all = [cfg.golden, ...cfg.items], results = new Array(all.length);
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(cfg.concurrency ?? 1, all.length) }, async () => { for (;;) { const i = next++; if (i >= all.length) return; results[i] = await runItem(all[i], i); } }));
  const goldenAccepted = results[0].outcome === 'accepted';
  const ok = results.every(r => r.outcome !== 'error' && r.drift === null);
  return { verdict: ok ? 'PASS' : 'FAIL', goldenAccepted, items: results, spentCredits: Number(results.reduce((t, r) => t + r.credits, 0).toFixed(2)) };
}

// ---- the files ----
export const controlsFile = (out, shaHex, version) => join(out, `controls-${shaHex.slice(0, 7)}-${version.slice(0, 8)}.json`);
// The result next to gate2-result.json: one compact line for another program, and a per-candidate copy for the resume rule.
export function writeControls(out, { sha: shaHex, version, manifest, result, at }) {
  mkdirSync(out, { recursive: true });
  const line = `${JSON.stringify({ schema: CONTROLS_SCHEMA, candidateSha: shaHex, previewVersion: version, manifest, verdict: result.verdict, goldenAccepted: result.goldenAccepted, spentCredits: result.spentCredits, items: result.items, finishedAt: at.toISOString() })}\n`;
  writeFileSync(join(out, 'controls-result.json'), line);
  writeFileSync(controlsFile(out, shaHex, version), line);
}
// A candidate whose controls already PASSED with this same manifest is not reviewed again (reviewed once per candidate).
export function passedBefore(out, shaHex, version, manifestHash) {
  const file = controlsFile(out, shaHex, version);
  if (!existsSync(file)) return null;
  try { const r = JSON.parse(readFileSync(file, 'utf8')); return r.verdict === 'PASS' && (r.manifest?.hash ?? null) === (manifestHash ?? null) ? r : null; } catch { return null; }
}
export const spendLine = (item, index, shaHex, version, total, time) => `| c${index} | ${time} | ${shaHex} | ${version} | CONTROL: ${item.name.replace(/\|/g, '/')} (direct review call, outside the ledger) | - | ${item.outcome}${item.drift ? ' DRIFT' : ''} | 0 | ${item.credits.toFixed(2)} | - | ${item.artifactHash ? item.artifactHash.slice(0, 16) : '-'} | ${total.toFixed(2)} |\n`;
export const appendSpend = (out, lines) => appendFileSync(join(out, 'spend-rows.md'), lines.join(''));
export const manifestInfo = file => ({ path: resolve(file), hash: sha(readFileSync(file, 'utf8')) });
