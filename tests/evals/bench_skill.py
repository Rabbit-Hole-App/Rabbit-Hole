"""Benchmark for skills/small (docs/features/skill-bench.md): the eval's
scenarios, run N times per cell across a with-skill and a no-skill arm,
scored as pass rates + skill lift + cost, written to results/*.json (raw
reps) and benchmark.md (the human report).

Costs real tokens - a full run is scenarios x arms x reps headless agents.
Always start with --dry-run. Hand-triggered only, never CI.

    .venv/Scripts/python tests/evals/bench_skill.py --dry-run
    .venv/Scripts/python tests/evals/bench_skill.py -n 1 --scenario plain   # smoke
    .venv/Scripts/python tests/evals/bench_skill.py                          # full: 6 x 2 x 5

Flags: -n REPS (5) · --scenario NAME (repeatable) · --arms skill,noskill ·
--model ID (EVAL_MODEL / claude-sonnet-5) · --dry-run
"""

import argparse
import json
import shutil
import statistics
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import date
from pathlib import Path

from scenarios import MODEL, SCENARIOS, run_scenario, skill_hash, violations

HERE = Path(__file__).resolve().parent
EST_USD_PER_RUN = 0.45  # dry-run estimate (smoke-measured, sonnet); the report uses real cost


def one_rep(name, arm, model):
    try:
        ctx = run_scenario(name, skill=(arm == "skill"), model=model, json_output=True)
    except Exception as e:  # noqa: BLE001 - a crashed rep is a failed rep, the grid keeps going
        return {"scenario": name, "arm": arm, "checks": {}, "passed": False,
                "violations": [], "cost_usd": None, "duration_s": None, "turns": None, "error": str(e)[:200]}
    checks = {label: ok for label, ok in SCENARIOS[name]["checks"](ctx)}
    rec = {
        "scenario": name, "arm": arm,
        "checks": checks, "passed": all(checks.values()),
        "violations": violations(ctx) if arm == "noskill" else [],
        "cost_usd": ctx["cost_usd"], "duration_s": ctx["duration_s"], "turns": ctx["turns"],
    }
    shutil.rmtree(ctx["work"], ignore_errors=True)
    return rec


def med(vals):
    vals = [v for v in vals if v is not None]
    return round(statistics.median(vals), 2) if vals else None


def rate(recs):
    return f"{sum(r['passed'] for r in recs)}/{len(recs)}"


def pct(recs):
    return 100 * sum(r["passed"] for r in recs) / len(recs) if recs else 0


def report_md(records, model, reps, arms):
    names = sorted({r["scenario"] for r in records}, key=list(SCENARIOS).index)
    by = lambda n, a: [r for r in records if r["scenario"] == n and r["arm"] == a]
    lines = [
        "# skills/small benchmark",
        "",
        f"date {date.today().isoformat()} · model {model} · skill {skill_hash()} · {reps} reps/cell",
        "",
        "Regenerated by `tests/evals/bench_skill.py`; raw reps in `results/`.",
        "Spec: `docs/features/skill-bench.md`.",
        "",
        "| scenario | skill | noskill | lift | $ med | s med | turns med |",
        "|---|---|---|---|---|---|---|",
    ]
    for n in names:
        s, ns = by(n, "skill"), by(n, "noskill")
        lift = f"{pct(s) - pct(ns):+.0f}pp" if s and ns else "-"
        lines.append(
            f"| {n} | {rate(s) if s else '-'} | {rate(ns) if ns else '-'} | {lift} "
            f"| {med([r['cost_usd'] for r in s])} | {med([r['duration_s'] for r in s])} | {med([r['turns'] for r in s])} |"
        )
    sk, nk = [r for r in records if r["arm"] == "skill"], [r for r in records if r["arm"] == "noskill"]
    if sk and nk:
        lines += ["", f"**Overall lift: {pct(sk) - pct(nk):+.0f}pp** (skill {rate(sk)}, noskill {rate(nk)})"]
    total = sum(r["cost_usd"] or 0 for r in records)
    lines += ["", f"Total measured cost: ${total:.2f} across {len(records)} runs."]

    viol = [v for r in records for v in r["violations"]]
    if viol:
        lines += ["", "## No-skill violations", ""]
        for v in sorted(set(viol)):
            lines.append(f"- {v}: {viol.count(v)}x")

    lines += ["", "## Per-assertion (skill arm failures first)", ""]
    for n in names:
        s = by(n, "skill")
        if not s:
            continue
        lines.append(f"### {n}")
        labels = list(s[0]["checks"]) if s[0]["checks"] else []
        for label in labels:
            k = sum(1 for r in s if r["checks"].get(label))
            mark = "" if k == len(s) else "  ← flaky"
            lines.append(f"- {label}: {k}/{len(s)}{mark}")
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-n", type=int, default=5)
    ap.add_argument("--scenario", action="append", choices=list(SCENARIOS))
    ap.add_argument("--arms", default="skill,noskill")
    ap.add_argument("--model", default=MODEL)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    names = a.scenario or list(SCENARIOS)
    arms = [x for x in a.arms.split(",") if x in ("skill", "noskill")]
    grid = [(n, arm) for n in names for arm in arms for _ in range(a.n)]
    print(f"grid: {len(names)} scenarios x {arms} x {a.n} reps = {len(grid)} runs "
          f"(~${len(grid) * EST_USD_PER_RUN:.0f} est) on {a.model}, skill {skill_hash()}")
    if a.dry_run:
        for n in names:
            print(f"  {n}: {SCENARIOS[n]['title']}")
        return 0

    with ThreadPoolExecutor(max_workers=4) as ex:
        futs = [ex.submit(one_rep, n, arm, a.model) for n, arm in grid]
        records = []
        for i, f in enumerate(futs, 1):
            r = f.result()
            records.append(r)
            cost = f"${r['cost_usd']:.2f}" if r["cost_usd"] else "?"
            print(f"[{i}/{len(grid)}] {r['scenario']}/{r['arm']}: {'pass' if r['passed'] else 'FAIL'} {cost}")

    results_dir = HERE / "results"
    results_dir.mkdir(exist_ok=True)
    out = results_dir / f"bench-{date.today().isoformat()}-{skill_hash()}.json"
    # same-day same-skill runs merge, so the grid can be run in scenario chunks
    if out.exists():
        records = json.loads(out.read_text(encoding="utf-8"))["records"] + records
    out.write_text(json.dumps({"model": a.model, "reps": a.n, "skill": skill_hash(),
                               "records": records}, indent=2), encoding="utf-8")
    (HERE / "benchmark.md").write_text(report_md(records, a.model, a.n, arms), encoding="utf-8")
    print(f"\nwrote {out}\nwrote {HERE / 'benchmark.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
