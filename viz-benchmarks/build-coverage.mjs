// Regenerates COVERAGE.md from patterns.json and benchmark-registry.json.
// The split that matters: a case we drew ourselves proves our machinery works.
// Only a case captured from a published visualization proves we can match one.
import { readFileSync, writeFileSync } from 'node:fs';

const patterns = JSON.parse(readFileSync(new URL('./patterns.json', import.meta.url), 'utf8')).patterns;
const registry = JSON.parse(readFileSync(new URL('./benchmark-registry.json', import.meta.url), 'utf8'));

const cases = registry.projects.flatMap(project => (project.cases || []).map(entry => ({ project: project.id, ...entry })));
const label = entry => `${entry.project}/${entry.id}`;
const ready = type => cases.filter(entry => entry.status === 'ready' && entry.referenceType === type);
const candidatesFor = id => registry.projects.filter(p => (p.candidatePatterns || []).includes(id) && !(p.cases || []).some(c => c.status === 'ready')).map(p => p.id);

// A case can declare a pattern it has no way to demonstrate - routing,
// zoom_drilldown and coordinated_views need branching, drill-down or linked
// views none of the current static cases can show. patternAssessability
// records that per pattern id without touching `patterns` itself (every
// other reader of `patterns` still sees a plain list of declared ids). Only
// an explicit `assessable: false` excludes a declaration from coverage; its
// absence means ordinary, assessable coverage, same as before this field
// existed.
const isAssessable = (entry, patternId) => entry.patternAssessability?.[patternId]?.assessable !== false;
const declaredHas = (entry, patternId) => entry.patterns.includes(patternId);

const rows = patterns.map(pattern => ({
  pattern,
  external: ready('external_real').filter(c => declaredHas(c, pattern.id) && isAssessable(c, pattern.id)),
  synthetic: ready('synthetic_internal').filter(c => declaredHas(c, pattern.id) && isAssessable(c, pattern.id)),
  unassessable: cases.filter(c => c.status === 'ready' && declaredHas(c, pattern.id) && !isAssessable(c, pattern.id)),
  blocked: (registry.blockedPatterns || []).includes(pattern.id),
  candidates: candidatesFor(pattern.id),
}));

const externalCovered = rows.filter(row => row.external.length).length;
const syntheticOnly = rows.filter(row => !row.external.length && row.synthetic.length).length;

let md = `# Pattern coverage

The suite exists to cover reusable visualization patterns. Counting cases measures
nothing; this table is the measure.

**Two kinds of coverage, never added together.** A case whose reference we drew
ourselves proves our machinery runs end to end. Only a case captured from a
published visualization proves the visual language can match a system somebody
else already shipped. Conflating them is how a suite starts reporting progress it
has not made.

Generated by \`build-coverage.mjs\`. Run it rather than editing this file.

## External coverage — measured against real published visualizations

**${externalCovered} of ${rows.length} patterns.**

| pattern | external cases | candidate projects |
|---|---|---|
`;
for (const row of rows) {
  md += `| **${row.pattern.name}** | ${row.external.map(label).join('<br>') || '—'} | ${row.candidates.join(', ') || '—'} |\n`;
}

md += `
## Internal coverage — our own reconstructions, for regression only

**${syntheticOnly} further patterns** have a synthetic case and no external one. These
prove the machinery, not the result.

| pattern | synthetic cases |
|---|---|
`;
for (const row of rows.filter(r => r.synthetic.length)) {
  md += `| **${row.pattern.name}** | ${row.synthetic.map(label).join('<br>')} |\n`;
}

const unassessable = rows.filter(row => row.unassessable.length);
if (unassessable.length) {
  md += `
## Declared, not assessable

A case can only prove a pattern it is able to show. These declare a pattern a
**static** case has no way to demonstrate - no branching, no drill-down, no
linked views - so the declaration is recorded but excluded from the coverage
totals above, rather than counted as tested.

| pattern | case | reason |
|---|---|---|
`;
  for (const row of unassessable) {
    for (const c of row.unassessable) {
      md += `| **${row.pattern.name}** | ${label(c)} | ${c.patternAssessability[row.pattern.id].reason} |\n`;
    }
  }
}

md += `
## Blocked, and by what

**Parameter exploration** and **coordinated views** need a learner input that changes
the picture. The runtime has no input axis until Plan B, so a benchmark for either
would measure something that does not exist. Capture their references now and mark
the case \`blocked_by: input_axis\`; do not run them.

The rest are uncovered only because nothing has been captured yet. They are the
queue, one project at a time.
`;
writeFileSync(new URL('./COVERAGE.md', import.meta.url), md);
console.log(`external ${externalCovered}/${rows.length}, synthetic-only ${syntheticOnly}`);
